export function systemPrompt(settings: Settings): string {
  const parts = [BASE, DIALECTS[settings.dialect] ?? DIALECTS.emirati, CONTROL]
  if (settings.webSearch) parts.push(SEARCH)
  if (settings.persona.trim()) {
    parts.push(
      `\nتعليمات إضافية من المستخدم (لها الأولوية على أسلوبك الافتراضي):\n${settings.persona.trim()}`,
    )
  }
  return parts.join('\n')
}

/**
 * حالة اللحظة — تُرفق بآخر رسالة للمستخدم لا بتعليمات النظام،
 * حتى تبقى البادئة المخزّنة مؤقتًا سليمة.
 */
export function contextBlock(input: {
  userName: string
  memories: string[]
  reminders: string[]
}): string {
  const now = new Date()
  const lines = [
    '<حالة_الآن>',
    `الوقت: ${now.toLocaleString('ar', { hour12: false })}`,
    `المنصّة: ${process.platform === 'win32' ? 'ويندوز' : process.platform}`,
  ]
  if (input.userName.trim()) lines.push(`المستخدم: ${input.userName.trim()}`)
  if (input.reminders.length) lines.push(`تذكيرات قادمة: ${input.reminders.join(' · ')}`)
  if (input.memories.length) lines.push(`تعرف عنه: ${input.memories.slice(0, 12).join(' · ')}`)
  lines.push('</حالة_الآن>')
  return lines.join('\n')
}
