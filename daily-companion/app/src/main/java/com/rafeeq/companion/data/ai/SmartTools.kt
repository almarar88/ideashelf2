package com.rafeeq.companion.data.ai

/**
 * أدوات النصّ الذكية.
 *
 * كانت هذه القدرات موجودة لكن مخبوءة: لا تظهر إلا حين تشارك نصًّا من تطبيق
 * آخر، وثلاثًا فقط. فمن أراد تلخيص شيء في يده يفتح المحادثة ويكتب تعليماته
 * بنفسه كل مرّة — وهو ما يفعله الناس فعلًا، ويكتبونه ناقصًا فيحصلون على
 * نتيجة متقلّبة.
 *
 * هنا تصير قسمًا قائمًا بذاته: ألصق نصًّا واضغط زرًّا. والتعليمات مكتوبة
 * مرّةً بعناية بدل أن تُرتجل، فالنتيجة ثابتة الجودة.
 */
object SmartTools {

    data class Tool(
        val id: String,
        val label: String,
        val emoji: String,
        /** سطر يشرح للمستخدم ما تفعله الأداة قبل أن ينفق عليها رموزًا. */
        val hint: String,
        /** التعليمات التي تُرسل للنموذج قبل النصّ. */
        val instruction: String,
    )

    /**
     * النصّ الطويل يُقتطع.
     *
     * بلا حدٍّ يلصق المستخدم كتابًا فيُرفض الطلب برسالة من المزوّد عن تجاوز
     * السياق، أو يمرّ ويكلّفه أضعاف ما توقّع. القطع مع إخباره أصدق.
     */
