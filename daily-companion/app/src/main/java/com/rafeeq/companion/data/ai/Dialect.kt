package com.rafeeq.companion.data.ai

/**
 * لهجة المساعد.
 *
 * اللهجة تأتي من **صياغة النص** لا من محرّك النطق: محرّكات أندرويد العربية
 * تنطق بلكنة فصيحة قريبة من المصرية أو الخليجية بحسب الجهاز، ولا يمكن لتطبيق
 * أن يغيّر ذلك. لكن حين يكتب المساعد «شحالك؟ عيل بروح أسوي لك ذي» بدل
 * «كيف حالك؟ إذن سأقوم بذلك» يصبح المسموع إماراتيًا في مفرداته وإيقاعه.
 *
 * لذلك نطلب من النموذج لهجةً معجميةً وتركيبية، ونضبط لغة النطق على
 * ar-AE ليختار الجهاز أقرب صوت متاح.
 */
enum class Dialect(
    val key: String,
    val arabic: String,
    val sample: String,
    /** لغة التعرّف والنطق التي نطلبها من النظام. */
    val bcp47: String,
) {
    EMIRATI("emirati", "إماراتي", "شحالك؟ عساك بخير — أبشر، بسويها لك الحين.", "ar-AE"),
    GULF("gulf", "خليجي عام", "شلونك؟ زين — أبشر، أسويها لك الحين.", "ar-SA"),
    FUSHA("fusha", "فصحى", "كيف حالك؟ حسنًا — سأنفّذ ذلك الآن.", "ar-SA"),
    EGYPTIAN("egyptian", "مصري", "إزيك؟ تمام — ماشي، هعملها لك دلوقتي.", "ar-EG"),
    LEVANTINE("levantine", "شامي", "كيفك؟ منيح — تمام، رح ساويها هلق.", "ar-JO");

    companion object {
        fun from(value: String?): Dialect =
            entries.firstOrNull { it.key == value } ?: EMIRATI
    }
}

/**
 * تعليمات اللهجة التي تُحقن في بادئة النظام.
 *
 * مكتوبة كمعجم لا كوصف: «قل كذا بدل كذا» ينتج لهجة أدقّ بكثير من
 * «تحدّث باللهجة الإماراتية»، لأن الأخيرة تعطي كليشيهات لا كلامًا حقيقيًا.
 */
object DialectPrompt {

    fun instructions(dialect: Dialect): String = when (dialect) {
        Dialect.EMIRATI -> EMIRATI
        Dialect.GULF -> GULF
        Dialect.FUSHA -> FUSHA
        Dialect.EGYPTIAN -> EGYPTIAN
        Dialect.LEVANTINE -> LEVANTINE
    }

    /** قاعدة مشتركة: النصّ قد يُنطق، فيجب أن يكون صالحًا للنطق. */
    private const val SPEAKABLE = """
اكتب بحروف عربية فقط. لا تستخدم چ ولا گ ولا ڤ ولا حروفًا غير عربية،
لأن محرّك النطق يلفظها خطأً أو يتجاهلها. اكتب «كيف» لا «چيف».
"""

    private val EMIRATI = """
<اللهجة>
تكلّم باللهجة الإماراتية المحكية في الإمارات، لا بالفصحى ولا بلهجة خليجية عامة.
لست مترجمًا للفصحى — فكّر بالإماراتي مباشرة.

المفردات الأساسية (استخدمها، لا تشرحها):
- كيف حالك ← شحالك (للرجل) / شحالچ تُكتب: شحالك
- ما الأخبار ← شخبارك · ما هذا ← شو هذا / شو ذا · لماذا ← ليش أو شحقّه
- الآن ← الحين · بعد ← عقب · هكذا ← جذي · هنا ← هني · أين ← وين
- كثير ← وايد · جيد ← زين · ليس ← مب · إذن ← عيل · أريد ← أبا / أبغي
- سأفعل ← بسوي · افعل ← سوّ · انظر ← شوف · تعال ← تعال · اذهب ← روح
- هذا ← ذا / هذي ← ذي · قليل ← شوي · بسرعة ← على طول / سيده
- انتهى ← خلاص · حسنًا ← زين / أوكي · فورًا ← الحين حالاً

عبارات المجاملة الإماراتية (وزّعها بلا إفراط — واحدة تكفي في الرد):
عساك بخير · حياك الله · أبشر · من عيوني · على راسي · ما قصرت ·
يزاك الله خير · تسلم · الله يعافيك · بالتوفيق · دام عزك

الإيقاع: جمل قصيرة، ودّ بلا تكلّف، بلا مقدمات. حين تنفّذ أمرًا قل
«أبشر، سويتها» أو «تم، شغّلته» — لا «لقد قمت بتنفيذ طلبك بنجاح».
$SPEAKABLE
</اللهجة>
"""

    private val GULF = """
<اللهجة>
تكلّم بلهجة خليجية عامة يفهمها أهل الخليج كلهم.
شلونك · وش الأخبار · الحين · وايد · زين · مب · أبغى · بسوي · شوف · وين · ليش.
عبارات: أبشر · من عيوني · على راسي · ما قصرت · تسلم.
جمل قصيرة وودّ بلا تكلّف. حين تنفّذ أمرًا قل «تم، سويتها».
$SPEAKABLE
</اللهجة>
"""

    private val FUSHA = """
<اللهجة>
تكلّم بالعربية الفصحى المبسّطة: واضحة، قصيرة الجمل، بلا تقعّر ولا سجع.
$SPEAKABLE
</اللهجة>
"""

    private val EGYPTIAN = """
<اللهجة>
تكلّم بالمصرية العامية: إزيك · إيه · دلوقتي · كده · أوي · مش · عايز ·
هعمل · بص · فين · ليه · تمام · ماشي. جمل قصيرة وخفيفة الظل بلا مبالغة.
$SPEAKABLE
</اللهجة>
"""

    private val LEVANTINE = """
<اللهجة>
تكلّم بالشامية: كيفك · شو · هلق · هيك · كتير · مش · بدي · رح ساوي ·
شوف · وين · ليش · منيح · تمام. جمل قصيرة ودافئة.
$SPEAKABLE
</اللهجة>
"""
}
